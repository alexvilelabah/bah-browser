export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('uiLang');
    if (saved === 'en' || saved === 'pt' || saved === 'es') return saved;
  } catch {}
  // Sem escolha explícita → segue o idioma do SISTEMA. A IA já responde no idioma da
  // pessoa; deixar a interface em inglês criava o pior dos mundos: resposta em português
  // com botão "Do this" embaixo — que ninguém entende (e um botão que DISPARA uma tarefa
  // no navegador não pode ser indecifrável). Escolha feita nas Configurações continua
  // mandando: só caímos aqui quando o usuário nunca escolheu.
  try {
    // Locale do SO via Electron. navigator.language NÃO serve: num Windows em português o
    // Chromium reporta "en-US" como principal (medido), então a detecção erraria justamente
    // pra quem ela existe. navigator fica só como rede de segurança.
    const sys = String(
      (window as any).electronAPI?.systemLocale || navigator.language || '',
    ).toLowerCase();
    if (sys.startsWith('pt')) return 'pt';
    if (sys.startsWith('es')) return 'es';
  } catch {}
  return 'en';
}

let currentLang: Lang = detectLang();

// Quem quiser re-renderizar quando o idioma mudar se inscreve aqui (a UI não recarrega
// — assim o menu/Configurações NÃO fecham ao trocar o idioma).
const langListeners = new Set<() => void>();
export function onLangChange(fn: () => void): () => void {
  langListeners.add(fn);
  return () => { langListeners.delete(fn); };
}

export function getLang(): Lang { return currentLang; }

export function setLang(l: Lang): void {
  currentLang = l;
  try { localStorage.setItem('uiLang', l); } catch {}
  langListeners.forEach(fn => { try { fn(); } catch {} });
}

// ── Locale de BUSCA pelo idioma da UI ──────────────────────────────────────
// Antes, TODA busca do agente (Pesquisa Rápida, notícias, compras, barra) estava
// cravada em pt-BR&gl=BR → trazia páginas em português pra quem usa em inglês/
// espanhol. Estes helpers derivam o locale do idioma ATUAL, em tempo de chamada.
const SEARCH_LOCALES: Record<Lang, { google: string; bing: string; name: string }> = {
  en: { google: 'hl=en', bing: 'en', name: 'English' },
  pt: { google: 'hl=pt-BR&gl=BR', bing: 'pt-BR', name: 'Brazilian Portuguese' },
  es: { google: 'hl=es', bing: 'es', name: 'Spanish' },
};
/** Parâmetros de locale do Google (hl/gl) pelo idioma da UI — ex.: "hl=en". */
export function googleLocaleParams(): string { return SEARCH_LOCALES[currentLang].google; }
/** Locale do Bing (setlang) pelo idioma da UI. */
export function bingLocale(): string { return SEARCH_LOCALES[currentLang].bing; }
/** Nome do idioma da UI em inglês ("English"/"Brazilian Portuguese"/"Spanish") — pra instruir o modelo a responder no idioma certo. */
export function uiLangName(): string { return SEARCH_LOCALES[currentLang].name; }

// Tradução. Cai pro inglês se faltar a chave no idioma; senão devolve a própria chave.
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = (dict[currentLang] && dict[currentLang][key]) || dict.en[key] || key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
  return s;
}

/** Os cinco passos do tour, no idioma atual (ícone + título + texto). */
export function tourSteps(): Array<{ icon: string; title: string; text: string }> {
  const icons = ['💬', '🗺️', '🛑', '🏠', '📋'];
  return [1, 2, 3, 4, 5].map((n, i) => ({
    icon: icons[i],
    title: t(`tour.${n}.t`),
    text: t(`tour.${n}.x`),
  }));
}
